def storage_text(gb):
    return (
        "1 تيرابايت"
        if gb == 1024
        else (f"{gb // 1024} تيرابايت" if gb % 1024 == 0 and gb > 1024 else f"{gb} جيجا")
    )


def _specs_mobile(m):
    brand, model, ram, st, scr, bat, cam, os_, net, *_, color, wty, seller, stock, active = m
    return dict(
        ram_gb=ram,
        storage_gb=st,
        screen_inch=scr,
        battery_mah=bat,
        camera_mp=cam,
        os=os_,
        network=net,
        color_ar=color,
    )


